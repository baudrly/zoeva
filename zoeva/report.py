import os, pandas as pd
from jinja2 import Template
from .config import ensure_dir

TEMPLATE = Template("""
# AI Scientist Report

**Run directory**: {{ run_dir }}

## Top hypotheses
{% for id, group in groups.items() %}
### {{ id }}
{% for t, recs in group.items() %}
**{{ t }}**:
{% for r in recs[:10] %} `{{ r['label'] }}` ({{ '%0.2f'|format(r['score']) }}){% if not loop.last %}, {% endif %}{% endfor %}

{% endfor %}
{% endfor %}

---
Generated by zoeva.
""")

def render_simple_report(scored_parquet: str, out_dir: str) -> str:
    ensure_dir(out_dir)
    df = pd.read_parquet(scored_parquet)
    groups = {}
    for id_, sub in df.groupby("id"):
        g = {}
        for t, sub2 in sub.groupby("type"):
            g[t] = sub2[["label","score","source"]].to_dict(orient="records")
        groups[id_] = g
    md = TEMPLATE.render(groups=groups, run_dir=os.path.abspath(out_dir))
    outf = os.path.join(out_dir, "report.md")
    with open(outf, "w", encoding="utf-8") as f:
        f.write(md)
    return outf
